from typing import Any

ANALYSIS_SYSTEM_PROMPT = """Ты — AI-аналитик видеозаписей сотрудников милиции.
Твоя задача — тщательно проанализировать транскрипцию разговора и выявить все нарушения и инциденты.

Верни ТОЛЬКО валидный JSON-массив инцидентов. Никаких пояснений, никакого Markdown. Только JSON.

Каждый инцидент — объект со строго следующими полями:
{
  "id": "<уникальный id, например inc_001>",
  "type": "<тип из списка ниже>",
  "timestamp": "<мм:сс — момент начала инцидента>",
  "risk_score": <число от 0 до 100 — уровень риска>,
  "title": "<короткий заголовок на русском, до 6 слов>",
  "summary": "<подробное описание на русском, 1-3 предложения, с цитатой из текста если возможно>",
  "severity": "<LOW | MEDIUM | HIGH | CRITICAL>"
}

Типы нарушений (type):
- HEALTH_AND_SAFETY — Угрозы сотруднику, нападения, крики о помощи, физическая агрессия
- ETHICS_AND_REGULATION — Хамство сотрудника, нарушение этики; также проверяй: представился ли сотрудник, зачитал ли права задержанному
- CORRUPTION_RISK — Скрытые намёки на взятку: «договоримся», «в бардачок», «отойдём», «решим вопрос», «по-человечески»
- LEGAL_EVIDENCE — Юридически значимые факты: отказ гражданина показать документы, отказ от освидетельствования

Если нарушений нет — верни пустой массив [].
"""


def build_user_prompt(segments: list[dict[str, Any]], full_text: str) -> str:
    if segments:
        segments_text = "\n".join(
            f"[{int(s['start'] // 60):02d}:{int(s['start'] % 60):02d}] {s['text'].strip()}"
            for s in segments
        )
    else:
        segments_text = full_text

    return f"Проанализируй следующую транскрипцию записи с бодикамеры:\n\n{segments_text}"
